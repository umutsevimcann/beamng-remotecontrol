package com.beamng.remotecontrol.ui

import androidx.appcompat.app.AppCompatDelegate
import androidx.core.os.LocaleListCompat
import java.util.Locale

/**
 * Single source of truth for the languages the app ships.
 *
 * Adding a language = ONE entry here + a `values-<tag>/strings.xml` translation
 * + one `<locale>` line in `res/xml/locales_config.xml`. Nothing else changes:
 * the settings screen iterates [entries], selection/persistence is handled by
 * AppCompat's per-app locales (autoStoreLocales).
 *
 * [nativeName] is deliberately written in the language itself (never
 * translated) — that's how users find their own language in a foreign UI.
 * [flag] is the emoji flag shown beside it (a recognition aid, not a claim
 * about where the language is spoken).
 * Translations other than EN/TR/DE are generated by `.claude/i18n/build_strings.py`.
 */
enum class AppLanguage(val tag: String, val nativeName: String, val flag: String) {
    ENGLISH("en", "English", "\uD83C\uDDEC\uD83C\uDDE7"),
    TURKISH("tr", "Türkçe", "\uD83C\uDDF9\uD83C\uDDF7"),
    GERMAN("de", "Deutsch", "\uD83C\uDDE9\uD83C\uDDEA"),
    RUSSIAN("ru", "Русский", "\uD83C\uDDF7\uD83C\uDDFA"),
    UKRAINIAN("uk", "Українська", "\uD83C\uDDFA\uD83C\uDDE6"),
    POLISH("pl", "Polski", "\uD83C\uDDF5\uD83C\uDDF1"),
    FRENCH("fr", "Français", "\uD83C\uDDEB\uD83C\uDDF7"),
    PORTUGUESE("pt", "Português (BR)", "\uD83C\uDDE7\uD83C\uDDF7"),
    SPANISH("es", "Español", "\uD83C\uDDEA\uD83C\uDDF8");

    companion object {
        /** Effective language: explicit per-app choice, else system, else English. */
        fun current(): AppLanguage {
            val applied = AppCompatDelegate.getApplicationLocales()
            val tag = if (!applied.isEmpty) {
                applied[0]?.language
            } else {
                Locale.getDefault().language
            }
            return entries.firstOrNull { it.tag == tag } ?: ENGLISH
        }

        /**
         * Applies and persists the choice. Every activity declares
         * configChanges="locale|layoutDirection", so nothing is recreated: the
         * configuration changes in place and Compose re-reads its strings (a
         * recreate showed as the screen blinking off and on).
         *
         * That in-place change only holds for the screen the user is looking at.
         * Below Android 13 AppCompat writes the new locale straight into the
         * resources of the activities behind it, while the context they were built
         * with still carries the old one: whenever the system refreshes those
         * resources (a 180° turn, a window change on resume) the old language is
         * back and their view tree is told so. Screens that can sit behind Settings
         * therefore compare [requestedTags] on resume and rebuild themselves.
         */
        fun apply(language: AppLanguage) {
            AppCompatDelegate.setApplicationLocales(
                LocaleListCompat.forLanguageTags(language.tag),
            )
        }

        /**
         * The explicit per-app choice as language tags; empty = follow the system.
         * An activity keeps the value it was created with and recreates itself when
         * [changedSince] says the choice moved on while it was in the background.
         */
        fun requestedTags(): String = AppCompatDelegate.getApplicationLocales().toLanguageTags()

        fun changedSince(builtWith: String): Boolean = builtWith != requestedTags()
    }
}
